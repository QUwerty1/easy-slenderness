<script setup lang="ts">
import type { TotpSetup } from '~/types/auth'

definePageMeta({ access: 'setup' })

const auth = useAuthStore()
const dialog = useSystemDialog()
// Tutors and admins get here right after the password check, before logging in
const mandatory = auth.stage === 'setup2fa'

const step = ref(1)
const setup = ref<TotpSetup | null>(null)
const code = ref('')
const error = ref('')
const backupCodes = ref<string[]>([])
const loading = ref(false)

onMounted(async () => {
  if (auth.user?.totp_enabled) return navigateTo('/account')
  try {
    setup.value = await auth.begin2fa()
  } catch (e) {
    await dialog.show(parseApiError(e).detail, 'Ошибка')
    await cancel()
  }
})

async function confirm() {
  if (!/^\d{6}$/.test(code.value.trim())) {
    error.value = 'Введите 6-значный код из приложения'
    return
  }
  loading.value = true
  try {
    backupCodes.value = await auth.confirm2fa(code.value.trim())
    step.value = 2
  } catch (e) {
    code.value = ''
    error.value = parseApiError(e).detail
  } finally {
    loading.value = false
  }
}

async function cancel() {
  if (mandatory) {
    await auth.logout()
    await navigateTo('/login')
  } else {
    await navigateTo('/account')
  }
}

async function finish() {
  await navigateTo(mandatory ? '/' : '/account')
}

function downloadCodes() {
  const blob = new Blob([backupCodes.value.join('\n') + '\n'], { type: 'text/plain' })
  const link = document.createElement('a')
  link.href = URL.createObjectURL(blob)
  link.download = 'backup-codes.txt'
  link.click()
  URL.revokeObjectURL(link.href)
}
</script>

<template>
  <v-container max-width="640">
    <h1 class="text-h4 mb-2">Включение двухфакторной аутентификации</h1>
    <p v-if="mandatory" class="text-medium-emphasis mb-4">
      Для вашей роли двухфакторная аутентификация обязательна. Включите её, чтобы продолжить.
    </p>
    <v-stepper v-model="step" :items="['Привязка приложения', 'Резервные коды']" hide-actions>
      <template #[`item.1`]>
        <p class="mb-4">
          Отсканируйте QR-код в приложении-аутентификаторе (Google Authenticator, Яндекс Ключ, Aegis
          и т. п.) и введите код, который оно покажет.
        </p>
        <div class="d-flex justify-center mb-4">
          <!-- eslint-disable-next-line vue/no-v-html -- SVG generated by our API -->
          <div v-if="setup" class="qr" v-html="setup.qr_svg" />
          <v-progress-circular v-else indeterminate color="primary" class="my-12" />
        </div>
        <p v-if="setup" class="text-body-2 text-medium-emphasis text-center mb-4">
          Ключ для ручного ввода: <code>{{ setup.secret }}</code>
        </p>
        <v-form @submit.prevent="confirm">
          <v-text-field
            v-model="code"
            label="Код из приложения"
            inputmode="numeric"
            autocomplete="one-time-code"
            maxlength="6"
            :error-messages="error"
            @update:model-value="error = ''"
          />
          <div class="d-flex justify-end ga-2">
            <v-btn :disabled="loading" @click="cancel">Отмена</v-btn>
            <v-btn
              color="primary"
              variant="flat"
              type="submit"
              :loading="loading"
              :disabled="!setup"
            >
              Далее
            </v-btn>
          </div>
        </v-form>
      </template>

      <template #[`item.2`]>
        <v-alert type="info" variant="tonal" class="mb-4">
          Сохраните резервные коды в надёжном месте. Каждый код можно использовать один раз вместо
          кода из приложения. Больше они показаны не будут.
        </v-alert>
        <v-sheet border rounded class="pa-4 mb-4">
          <v-row dense>
            <v-col v-for="backupCode in backupCodes" :key="backupCode" cols="6" class="text-center">
              <code class="text-body-1">{{ backupCode }}</code>
            </v-col>
          </v-row>
        </v-sheet>
        <div class="d-flex justify-end ga-2">
          <v-btn prepend-icon="mdi-download" @click="downloadCodes">Скачать</v-btn>
          <v-btn @click="cancel">Отмена</v-btn>
          <v-btn color="primary" variant="flat" @click="finish">Готово</v-btn>
        </div>
      </template>
    </v-stepper>
  </v-container>
</template>

<style scoped>
.qr :deep(svg) {
  width: 220px;
  height: 220px;
}
</style>
